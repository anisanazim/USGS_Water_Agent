"""Discrete data parameter families and catalog metadata.
Autogenerated from catalog codeservice and verified reference counts.
"""
from __future__ import annotations

import csv
import json
import logging
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class DiscreteParameter:
    pcode: str
    characteristic_name: str
    descriptor: str
    group: str
    medium: str
    unit_of_measure: str
    verified_records_nc: int = 0
    verified_stations_nc: int = 0
    verified_date: str = ""

    def format_citation(self, record_count: int | None = None) -> str:
        count_str = f"{record_count:,} records of " if record_count is not None else ""
        return f"{count_str}{self.descriptor} ({self.pcode}), {self.unit_of_measure}"


@dataclass(frozen=True)
class DiscreteFamily:
    name: str
    mixed_modality: bool
    parameters: dict[str, DiscreteParameter]
    aliases: list[str] = field(default_factory=list)
    major_pcodes: list[str] = field(default_factory=list)
    is_verified_core: bool = True


def _load_discrete_families() -> dict[str, DiscreteFamily]:
    """Load parameter families and constituent metadata dynamically from JSON reference store."""
    ref_file = (
        Path(__file__).resolve().parents[3]
        / "metadata"
        / "raw"
        / "references"
        / "discrete_families.json"
    )
    if not ref_file.exists():
        logger.warning("discrete_families.json not found at %s", ref_file)
        return {}

    try:
        with open(ref_file, "r", encoding="utf-8") as f:
            raw_data = json.load(f)
    except Exception as e:
        logger.error("Error reading %s: %s", ref_file, e)
        return {}

    families: dict[str, DiscreteFamily] = {}
    for fam_name, fam_data in raw_data.items():
        params: dict[str, DiscreteParameter] = {}
        for pcode, p_data in fam_data.get("parameters", {}).items():
            vc = p_data.get("verified_counts") or {}
            params[pcode] = DiscreteParameter(
                pcode=pcode,
                characteristic_name=p_data.get("characteristicName", ""),
                descriptor=p_data.get("characteristicNameUserSupplied", ""),
                group=p_data.get("characteristicGroup", ""),
                medium=p_data.get("medium", "water"),
                unit_of_measure=p_data.get("unit_of_measure", ""),
                verified_records_nc=vc.get("recordCount", 0),
                verified_stations_nc=vc.get("stationCount", 0),
                verified_date=vc.get("date", ""),
            )
        major_pcodes = fam_data.get("major_pcodes")
        if not major_pcodes:
            major_pcodes = sorted(
                params.keys(),
                key=lambda k: params[k].verified_records_nc,
                reverse=True,
            )
        families[fam_name] = DiscreteFamily(
            name=fam_data.get("family", fam_name),
            mixed_modality=fam_data.get("mixed_modality", False),
            parameters=params,
            aliases=fam_data.get("aliases", []),
            major_pcodes=major_pcodes,
            is_verified_core=fam_data.get("is_verified_core", True),
        )
    return families


DISCRETE_FAMILIES: dict[str, DiscreteFamily] = _load_discrete_families()

# Map alias -> family_name
ALIAS_TO_FAMILY: dict[str, str] = {}
for fam_name, fam in DISCRETE_FAMILIES.items():
    for alias in fam.aliases:
        ALIAS_TO_FAMILY[alias.lower()] = fam_name

# Map pcode -> family_name
PCODE_TO_FAMILY: dict[str, str] = {
    pcode: fam.name
    for fam in DISCRETE_FAMILIES.values()
    for pcode in fam.parameters
}


def get_family_for_pcode(pcode: str) -> DiscreteFamily | None:
    fam_name = PCODE_TO_FAMILY.get(pcode.zfill(5))
    return DISCRETE_FAMILIES.get(fam_name) if fam_name else None


def get_parameter(pcode: str) -> DiscreteParameter | None:
    fam = get_family_for_pcode(pcode)
    return fam.parameters.get(pcode.zfill(5)) if fam else None


def is_mixed_modality(family_or_pcode: str) -> bool:
    if family_or_pcode in DISCRETE_FAMILIES:
        return DISCRETE_FAMILIES[family_or_pcode].mixed_modality
    fam = get_family_for_pcode(family_or_pcode)
    return fam.mixed_modality if fam else False


@dataclass(frozen=True)
class DiscreteResolutionResult:
    status: Literal["resolved", "clarification_needed", "not_found"]
    query_type: Literal["spatial", "value", "count"]
    family: DiscreteFamily | None
    pcodes: list[str]
    candidates: list[dict[str, Any]] | None = None
    message: str | None = None


_PARAMETER_UNITS_CACHE: dict[str, str] | None = None


def _get_parameter_units_map() -> dict[str, str]:
    global _PARAMETER_UNITS_CACHE
    if _PARAMETER_UNITS_CACHE is not None:
        return _PARAMETER_UNITS_CACHE

    units: dict[str, str] = {}
    pcode_json = (
        Path(__file__).resolve().parents[3]
        / "metadata"
        / "raw"
        / "references"
        / "parameter-codes.json"
    )
    if pcode_json.exists():
        try:
            with open(pcode_json, "r", encoding="utf-8") as f:
                data = json.load(f)
                for feat in data.get("features", []):
                    props = feat.get("properties", {})
                    pid = props.get("id")
                    unit = props.get("unit_of_measure")
                    if pid and unit:
                        units[pid] = unit
        except Exception:
            pass
    _PARAMETER_UNITS_CACHE = units
    return units


def search_catalog_characteristics(term: str, limit: int = 15) -> list[dict[str, Any]]:
    """Search characteristics catalog for parameters outside the 9 verified families."""
    ref_path = (
        Path(__file__).resolve().parents[3]
        / "metadata"
        / "raw"
        / "references"
        / "characteristics_filtered.csv"
    )
    if not ref_path.exists():
        return []

    term_clean = term.strip().lower()
    STOPWORDS = {
        "usgs", "water", "data", "query", "search", "only", "exact", "show", "find",
        "parameter", "parameters", "characteristic", "characteristics", "record", "records",
        "name", "description", "matches", "containing", "such", "available", "site", "sites",
        "station", "stations"
    }
    if term_clean in STOPWORDS or len(term_clean) < 3:
        return []

    matches: list[dict[str, Any]] = []
    seen_pcodes: set[str] = set()
    units_map = _get_parameter_units_map()

    try:
        with open(ref_path, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                group = row.get("characteristicGroup", "").strip()
                if group == "Information":
                    continue
                pcode = row.get("parameterCode", "").strip()
                cname = row.get("characteristicName", "").strip()
                desc = row.get("characteristicNameUserSupplied", "").strip()
                if not pcode or pcode in seen_pcodes:
                    continue
                if term_clean in cname.lower() or term_clean in desc.lower():
                    seen_pcodes.add(pcode)
                    unit = units_map.get(pcode, "")
                    matches.append({
                        "pcode": pcode,
                        "descriptor": desc,
                        "group": group,
                        "characteristic_name": cname,
                        "unit": unit,
                    })
                    if len(matches) >= limit:
                        break
    except Exception:
        pass

    return matches


def resolve_discrete_parameter(
    term: str,
    query_type: Literal["spatial", "value", "count"] = "value",
) -> DiscreteResolutionResult:
    """Resolve a parameter term to a discrete parameter family and its parameter codes.

    Contract: Flat lookup table, no auto-resolution, no dominance threshold,
    and no merging across parameter codes.
    """
    term_clean = term.strip().lower()

    # Find matching family: priority 1 is exact family name or exact pcode
    family = None
    for fam_name, fam in DISCRETE_FAMILIES.items():
        if term_clean == fam_name.lower() or term_clean.replace(" ", "_") == fam_name.lower():
            family = fam
            break
        if any(term_clean == p.pcode for p in fam.parameters.values()):
            family = fam
            break

    # Priority 1b: Exact alias match (e.g. "ca", "mg", "do", "srp", "tp", "ec", "tss")
    if not family and term_clean in ALIAS_TO_FAMILY:
        family = DISCRETE_FAMILIES.get(ALIAS_TO_FAMILY[term_clean])

    # Priority 2: Whole-word family name match (e.g. "total phosphorus" -> "phosphorus")
    # Must use word boundaries so short family names like "ph" do not match inside "phosphorus" or "orthophosphate"
    if not family:
        for fam_name, fam in DISCRETE_FAMILIES.items():
            pattern = r'\b' + re.escape(fam_name.lower()) + r'\b'
            if re.search(pattern, term_clean):
                family = fam
                break

    # Priority 3: characteristic name or descriptor match
    if not family:
        for fam_name, fam in DISCRETE_FAMILIES.items():
            for p in fam.parameters.values():
                c_name = p.characteristic_name.lower()
                desc = p.descriptor.lower()
                if (len(term_clean) > 2 and (term_clean == c_name or term_clean in c_name)) or (len(term_clean) > 2 and (term_clean == desc or term_clean in desc and "," not in term_clean)):
                    family = fam
                    break
            if family:
                break

    if not family:
        # Step 3b: Parameters outside the 9 verified families (e.g. mercury)
        catalog_matches = search_catalog_characteristics(term)
        if catalog_matches:
            cap_term = term.strip().capitalize()
            candidates_formatted = "\n".join(
                [
                    f"- **{m['pcode']}**: {m['descriptor']}" + (f" ({m['unit']})" if m.get("unit") else "") + f" [{m['group']}]"
                    for m in catalog_matches[:10]
                ]
            )
            return DiscreteResolutionResult(
                status="clarification_needed",
                query_type=query_type,
                family=None,
                pcodes=[m["pcode"] for m in catalog_matches],
                candidates=catalog_matches,
                message=(
                    f"{cap_term} is not in the verified parameter catalog. "
                    f"The following parameter codes match this characteristic in the USGS registry:\n\n"
                    f"{candidates_formatted}\n\n"
                    f"Which parameter code would you like to query?"
                ),
            )
        return DiscreteResolutionResult(
            status="not_found",
            query_type=query_type,
            family=None,
            pcodes=[],
            message=f"No discrete parameter family matched '{term}'.",
        )

    # If the input term was an exact pcode, resolve that specific parameter code (unless spatial query)
    if term_clean in family.parameters and query_type != "spatial":
        exact_p = family.parameters[term_clean]
        return DiscreteResolutionResult(
            status="resolved",
            query_type=query_type,
            family=family,
            pcodes=[exact_p.pcode],
            message=f"Exact discrete parameter code '{exact_p.descriptor}' ({exact_p.pcode}) resolved.",
        )

    # Return all family pcodes ordered by priority (major_pcodes with primary at index 0)
    sorted_pcodes = family.major_pcodes if family.major_pcodes else sorted(
        family.parameters.keys(),
        key=lambda k: family.parameters[k].verified_records_nc,
        reverse=True,
    )
    return DiscreteResolutionResult(
        status="resolved",
        query_type=query_type,
        family=family,
        pcodes=sorted_pcodes,
        message=(
            f"Discrete parameter family '{family.name}' resolved with {len(sorted_pcodes)} parameter codes: "
            f"{', '.join(sorted_pcodes)}."
        ),
    )
